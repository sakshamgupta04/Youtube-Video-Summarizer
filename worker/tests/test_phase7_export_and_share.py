"""Unit test for Phase 7 export and share logic."""

import re

def generate_markdown(item: dict) -> str:
    """Python mirror of the client-side export to markdown function for verification."""
    def format_time(sec: float) -> str:
        m = int(sec // 60)
        s = int(sec % 60)
        return f"{m}:{s:02d}"

    title = item.get("title") or "Untitled Summary"
    source_type = item.get("source_type") or "video"
    duration_sec = item.get("duration_sec") or 0

    chapters_text = "\n\n".join(
        f"### Chapter {i + 1}: {ch['title']} ({format_time(ch['start'])} - {format_time(ch['end'])})\n\n{ch.get('summary', 'No chapter summary.')}"
        for i, ch in enumerate(item.get("chapters") or [])
    )

    key_points_text = "\n".join(
        f"- {kp}" for kp in (item.get("key_points") or [])
    )

    transcript_text = "\n\n".join(
        f"**[{format_time(seg['start'])}]** {seg['text']}"
        for seg in (item.get("transcript") or [])
    )

    return f"""# {title}

*Generated by EchoNotes*
*Type: {source_type} | Duration: {format_time(duration_sec)}*

---

## Executive Summary

{item.get("summary") or "No overall summary generated."}

---

## Key Points & Takeaways

{key_points_text or "No key points available."}

---

## Chapters

{chapters_text or "No chapters available."}

---

## Full Transcript

{transcript_text or "No transcript available."}
"""


def test_markdown_export_structure():
    item = {
        "title": "Deep Learning Lecture 1",
        "source_type": "youtube",
        "duration_sec": 1200,
        "summary": "This lecture covers artificial neural networks and backpropagation.",
        "key_points": [
            "Perceptrons use activation functions like ReLU.",
            "Backpropagation uses the chain rule to compute gradients."
        ],
        "chapters": [
            {
                "start": 0.0,
                "end": 600.0,
                "title": "Introduction to Neurons",
                "summary": "Discussion of biological and artificial neurons."
            },
            {
                "start": 600.0,
                "end": 1200.0,
                "title": "Gradient Descent Optimization",
                "summary": "Detailed look at backpropagation."
            }
        ],
        "transcript": [
            {"start": 0.0, "end": 15.0, "text": "Welcome to deep learning lecture."},
            {"start": 600.0, "end": 615.0, "text": "Now we move to optimization."}
        ]
    }

    md = generate_markdown(item)

    assert "# Deep Learning Lecture 1" in md
    assert "## Executive Summary" in md
    assert "## Key Points & Takeaways" in md
    assert "## Chapters" in md
    assert "## Full Transcript" in md
    assert "### Chapter 1: Introduction to Neurons (0:00 - 10:00)" in md
    assert "### Chapter 2: Gradient Descent Optimization (10:00 - 20:00)" in md
    assert "**[0:00]** Welcome to deep learning lecture." in md
    assert "**[10:00]** Now we move to optimization." in md
    assert "- Perceptrons use activation functions like ReLU." in md


def test_share_token_format():
    import uuid
    token = uuid.uuid4().hex[:16]
    assert len(token) == 16
    assert re.match(r"^[0-9a-f]{16}$", token)
